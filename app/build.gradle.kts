import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
    alias(libs.plugins.kotlin.compose)
}

val sourceUrl = providers.gradleProperty("chessreview.sourceUrl").orNull.orEmpty().trim()

val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.sangeetastudios.chessreview"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.sangeetastudios.chessreview"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        ndk { abiFilters += listOf("arm64-v8a", "x86_64") }
        buildConfigField("String", "SOURCE_URL", "\"$sourceUrl\"")
        buildConfigField("String", "STOCKFISH_SOURCE_URL", "\"https://github.com/sangeeta-studios/Stockfish/tree/sf_17.1\"")
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        // Stockfish ships as an executable named libstockfish.so; it must be extracted
        // to nativeLibraryDir so it can be exec'd.
        jniLibs.useLegacyPackaging = true
    }

    lint {
        abortOnError = true
        checkReleaseBuilds = true
    }
}

kotlin {
    compilerOptions { jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17) }
}

// GPL: every distributed build must point users at its source code.
tasks.matching { it.name in setOf("preReleaseBuild", "bundleRelease") }.configureEach {
    val url = sourceUrl // local copy keeps the action configuration-cache friendly
    doFirst {
        check(url.startsWith("https://")) {
            "Set chessreview.sourceUrl in gradle.properties to the public GitHub repo before building a release."
        }
    }
}

